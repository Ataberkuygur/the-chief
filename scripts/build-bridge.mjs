// Embeds tab-bridge/ into hooks/bridge-files.ts so The Chief can install the bridge on a machine that has none.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { join, relative } from 'node:path'
const root = new URL('../tab-bridge', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')
const files = {}
const walk = d => { for (const n of readdirSync(d).sort()) { const p = join(d, n); statSync(p).isDirectory() ? walk(p) : (files[relative(root, p).replaceAll(String.fromCharCode(92), '/')] = readFileSync(p, 'utf8')) } }
walk(root)
const version = createHash('sha1').update(JSON.stringify(files)).digest('hex').slice(0, 12)
writeFileSync(new URL('../hooks/bridge-files.ts', import.meta.url), `// Generated by scripts/build-bridge.mjs from tab-bridge/; do not edit.\nexport const BRIDGE_VERSION = ${JSON.stringify(version)}\nexport const BRIDGE_FILES: Record<string, string> = ${JSON.stringify(files, null, 1)}\n`)
console.log(Object.keys(files), version)
