// Bakes live/the-chief-live.html into hooks/live-template.ts, so the plugin can publish
// the live page itself (no model call) and republish it when the template changes.
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const html = readFileSync(join(root, 'live/the-chief-live.html'), 'utf8').replace(/\r\n/g, '\n')
const version = createHash('sha256').update(html).digest('hex').slice(0, 12)
writeFileSync(
  join(root, 'hooks/live-template.ts'),
  `// Generated by scripts/build-live.mjs from live/the-chief-live.html; do not edit.\n` +
    `export const LIVE_TEMPLATE_VERSION = ${JSON.stringify(version)}\n` +
    `export const LIVE_TEMPLATE = ${JSON.stringify(html)}\n`,
)
console.log(`live template ${version} (${html.length} chars)`)
